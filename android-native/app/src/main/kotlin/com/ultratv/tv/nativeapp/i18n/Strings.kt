/**
 * Lightweight inline translation table. We deliberately avoid the Android
 * resource framework because most of the UI text is inline in Compose;
 * externalising every literal would be a multi-day rewrite. Strings not in
 * the table fall through to their English literal — partial coverage is
 * better than no coverage.
 */
/** [pickable] : langues proposées dans les Réglages (Kanaani : arabe, anglais, hébreu). */
enum class AppLang(val code: String, val displayName: String, val rtl: Boolean = false, val pickable: Boolean = true) {
    System("system", "System (auto)", pickable = false),
    English("en", "English"),
    French("fr", "Français", pickable = false),
    Spanish("es", "Español", pickable = false),
    Arabic("ar", "العربية", rtl = true),
    Hebrew("he", "עברית", rtl = true);

    companion object {
        /** Android renvoie encore « iw » pour l'hébreu sur certaines versions. */
        fun fromCode(code: String): AppLang = entries.firstOrNull { it.code == (if (code == "iw") "he" else code) } ?: System
        /** Ordre affiché dans les Réglages. */
        val PICKER: List<AppLang> = listOf(Arabic, English, Hebrew)
    }
}

